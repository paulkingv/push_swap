long ft_atol (char *s)
{
    long n;
    int sign;
    int i;

    n = 0;
    sign = 1;
    i = 0;
    if (s[i] == '+' || s[i] == '-')
    {
        if (s[i] == '-')
            sign = -1;
        i++;
    }
    while (s[i] >= '0' && s[i] <= '9')
    {
        n = n * 10 + (s[i] - '0');
        i++;
    }
    return (n * sign);
}